#!/usr/bin/env python3
"""Renders RESULTS.md from kv_contention_summary.json. Called automatically
at the end of kv_link_sim.py / run_e8.sh -- RESULTS.md in this directory is
generated output, not something to hand-edit (edit this template instead)."""
import json
from datetime import datetime, timezone
from pathlib import Path


def render(summary_path: Path, out_path: Path):
    s = json.loads(Path(summary_path).read_text())

    lines = []
    lines.append("# E8 Results: KV-Cache Co-Tenancy on the CXL Link")
    lines.append("")
    lines.append(f"*Auto-generated by `kv_link_sim.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e8.sh` to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/kv_contention_summary.json`, `out/kv_contention_sweep.csv`, "
                 "`out/figures/`. Ran entirely on a laptop -- no GPU, no model weights, no network.")
    lines.append("")

    lines.append("## Run configuration")
    lines.append("")
    lines.append(f"- Models: {s['models']}")
    lines.append(f"- Link bandwidths swept: {s['bw_grid']} GB/s")
    lines.append(f"- Policies: {s['policies']}")
    lines.append(f"- Decode batch (expert traffic): {s['batch']}, residency {s['residency_pct']}%, "
                 f"expert precision `{s['expert_precision']}`")
    lines.append(f"- KV precision: `{s['kv_precision']}`, context lengths {s['context_lens']} "
                 f"(weights {s['context_weights']})")
    lines.append(f"- KV request arrival rate (ASSUMPTION, not measured): {s['kv_rate_per_sec']}/sec")
    lines.append(f"- Simulated wall-clock per run: {s['sim_seconds']} s, "
                 f"pooled across {s.get('n_seeds', 1)} seeds (base seed={s['seed']})")
    lines.append("")

    lines.append("## KV-cache formula sanity check")
    lines.append("")
    lines.append("`kv_bytes_per_token = 2 * n_layers * num_key_value_heads * head_dim * bytes_per_element` "
                 "(Experiments.md E8 step 1's formula, minus the context_len factor -- see design doc for why "
                 "that's the right way to read it).")
    lines.append("")
    lines.append("| Model | KV bytes/token (fp16) | KV bytes/token (fp8) | " +
                 " | ".join(f"Total @ {c:,} tok (fp16)" for c in s["context_lens"]) + " |")
    lines.append("|---|---|---|" + "---|" * len(s["context_lens"]))
    for model, d in s["kv_formula_check"].items():
        totals = " | ".join(f"{d['kv_total_bytes_by_context_len_fp16'][str(c)]/1e9:.2f} GB"
                             for c in s["context_lens"])
        lines.append(f"| {model} | {d['kv_bytes_per_token_fp16']/1e3:.2f} KB | "
                     f"{d['kv_bytes_per_token_fp8']/1e3:.2f} KB | {totals} |")
    lines.append("")
    vals = {m: d["kv_bytes_per_token_fp16"] for m, d in s["kv_formula_check"].items()}
    if len(set(vals.values())) == 1 and len(vals) > 1:
        lines.append("> **Note:** every model listed above lands on the *same* KV bytes/token. This is a "
                     "genuine architectural coincidence for OLMoE vs Mixtral specifically (OLMoE: 16 layers "
                     "x 16 KV heads = 256; Mixtral: 32 layers x 8 KV heads (GQA) = 256 -- same product), "
                     "not a computation bug. Verified against both models' live HF `config.json`. Don't "
                     "expect this to hold for arbitrary model pairs.")
        lines.append("")

    lines.append("## Expert-traffic model per decode token (reused from E1)")
    lines.append("")
    lines.append("| Model | Expert job size/token | Job period (t_compute, all layers) | "
                 "t_compute source | E_union(B) |")
    lines.append("|---|---|---|---|---|")
    for model, t in s["per_model_traffic"].items():
        lines.append(f"| {model} | {t['expert_job_bytes']/1e6:.2f} MB | {t['expert_period_ms']:.4f} ms | "
                     f"`{t['compute_provenance']}` | {t['e_union_val']:.2f} |")
    lines.append("")

    lines.append("## Policy sweep: TTFT (KV) vs TPOT inflation (expert)")
    lines.append("")
    lines.append("TTFT here is the **link-contention component only** (arrival of a request's KV transfer "
                 "job to its completion) -- not full end-to-end TTFT, which also includes prefill compute "
                 "not modeled here. TPOT inflation is the extra time (beyond an isolated, contention-free "
                 "transfer) added to one decode token's expert fetch by KV traffic sharing the link. "
                 "`*` marks Pareto-optimal policies (no other policy at that model/bandwidth improves both "
                 "metrics at once).")
    lines.append("")
    lines.append("| Model | BW (GB/s) | Policy | TTFT p50 (ms) | TTFT p95 (ms) | "
                 "TPOT inflation p50 (ms/tok) | TPOT inflation p95 (ms/tok) | n(KV) | n(expert) | Pareto |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for row in sorted(s["sweep"], key=lambda r: (r["model"], r["bw_gbps"], r["policy"])):
        star = "**★**" if row["pareto_optimal"] else ""
        lines.append(f"| {row['model']} | {row['bw_gbps']:g} | {row['policy']} | "
                     f"{row['ttft_p50_ms']:.3f} | {row['ttft_p95_ms']:.3f} | "
                     f"{row['tpot_inflation_p50_ms']:.5f} | {row['tpot_inflation_p95_ms']:.5f} | "
                     f"{row['n_kv_completions']} | {row['n_expert_completions']} | {star} |")
    lines.append("")

    lines.append("## Isolated baselines (no cross-class contention)")
    lines.append("")
    lines.append("Reference points: each traffic class run alone on the link (self-queueing within a "
                 "class -- e.g. two KV jobs arriving close together -- can still show up here; that's real "
                 "contention too, just not *cross-class* contention).")
    lines.append("")
    lines.append("| Model | BW (GB/s) | Expert-alone inflation p50 (ms/tok) | KV-alone latency p50 (ms) |")
    lines.append("|---|---|---|---|")
    for row in s["isolated_baselines"]:
        lines.append(f"| {row['model']} | {row['bw_gbps']:g} | "
                     f"{row['expert_isolated']['inflation_p50_ms']:.5f} | "
                     f"{row['kv_isolated']['latency_p50_ms']:.3f} |")
    lines.append("")

    lines.append("## Recommendation")
    lines.append("")
    lines.append("Experiments.md's exit criteria: *\"A stated priority rule with quantified TTFT/TPOT "
                 "trade-off.\"* A single scalar \"best\" policy isn't well-defined without a TTFT budget "
                 "to trade against (see `kv_link_sim.recommend_policy`'s docstring for two scalarizations "
                 "that were tried and rejected as degenerate) -- so:")
    lines.append("")
    slo = s.get("ttft_slo_ms")
    if slo is None:
        lines.append("**No `--ttft-slo-ms` was given for this run.** Reporting the two Pareto extremes per "
                     "(model, bandwidth) instead of one arbitrary pick -- re-run with `--ttft-slo-ms <ms>` "
                     "to collapse this to a single recommendation once you have an actual TTFT budget.")
        lines.append("")
        lines.append("| Model | BW (GB/s) | Pareto set | Best-for-TTFT | Best-for-TPOT |")
        lines.append("|---|---|---|---|---|")
        for rec in s["recommendations"].values():
            bt, bp = rec["best_for_ttft"], rec["best_for_tpot"]
            lines.append(f"| {rec['model']} | {rec['bw_gbps']:g} | {rec['pareto_policies']} | "
                         f"`{bt['policy']}` ({bt['ttft_p50_ms']:.1f} ms TTFT, "
                         f"{bt['tpot_inflation_p50_ms']:.5f} ms/tok) | "
                         f"`{bp['policy']}` ({bp['ttft_p50_ms']:.1f} ms TTFT, "
                         f"{bp['tpot_inflation_p50_ms']:.5f} ms/tok) |")
    else:
        lines.append(f"TTFT p50 SLO = {slo} ms. Recommendation = argmin TPOT inflation among Pareto-optimal "
                     "policies meeting the SLO (falls back to best-achievable-TTFT if none do).")
        lines.append("")
        for rec in s["recommendations"].values():
            lines.append(f"- **{rec['model']} @ {rec['bw_gbps']:g} GB/s**: Pareto set = {rec['pareto_policies']}. "
                         f"Recommended: `{rec['recommended_policy']}` "
                         f"(TTFT p50={rec['recommended_ttft_p50_ms']:.3f} ms, "
                         f"TPOT inflation p50={rec['recommended_tpot_inflation_p50_ms']:.5f} ms/token). "
                         f"*{rec['note']}*")
    lines.append("")

    lines.append("## Figures")
    lines.append("")
    for fig in s["figures"]:
        lines.append(f"- `out/figures/{Path(fig).name}`")
    lines.append("")

    lines.append("## Analysis notes (fill in after reviewing the figures)")
    lines.append("")
    lines.append("- [ ] Is there a policy that's Pareto-optimal across *every* (model, bandwidth) pair, "
                 "or does the recommendation change with bandwidth (as the roofline's own regime-dependence "
                 "would predict)?")
    lines.append("- [ ] How much does the `--kv-rate-per-sec` assumption (currently "
                 f"{s['kv_rate_per_sec']}/sec, not measured) move the recommendation? Re-run with a "
                 "different value before quoting a single number in the report.")
    lines.append("- [ ] At the lowest swept bandwidth, does even `expert-first` show non-trivial TTFT "
                 "(i.e., is KV self-queueing, not expert contention, the dominant TTFT cost)?")
    lines.append("- [ ] Cross-reference against E1/E2: does the (batch, residency) operating point used "
                 "here fall on the latency-hideable or bandwidth-bound side of the roofline? If "
                 "bandwidth-bound already, KV contention only makes a bad regime worse -- say so.")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="experiments/e8_kv_cotenancy/out/kv_contention_summary.json")
    ap.add_argument("--out", default="experiments/e8_kv_cotenancy/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.summary), Path(args.out))
