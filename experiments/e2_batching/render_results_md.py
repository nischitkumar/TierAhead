#!/usr/bin/env python3
"""Renders RESULTS.md from batching_summary.json. Called automatically at the
end of batching_sweep.py / run_e2.sh -- RESULTS.md is generated output, not
something to hand-edit (edit this template instead)."""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.results_md import preserve_analysis_section  # noqa: E402


def render(summary_path: Path, out_path: Path):
    summary = json.loads(Path(summary_path).read_text())
    out_path = Path(out_path)

    lines = []
    lines.append("# E2 Results: Batching Sweet Spot")
    lines.append("")
    lines.append(f"*Auto-generated by `batching_sweep.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e2.sh` to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/batching_summary.json`, `out/bstar_table_{model}.csv`, `out/figures/`.")
    lines.append("")

    lines.append("## Claim check: \"fine-grained MoEs have a wide viable batch window, "
                 "coarse MoEs have none\"")
    lines.append("")
    lines.append("(Experiments.md E2 exit criteria: confirm or refute this with numbers.)")
    lines.append("")
    for line in summary["claim_check"]:
        lines.append(f"- {line}")
    lines.append("")

    for model, res in summary["per_model"].items():
        lines.append(f"## {model}")
        lines.append("")
        lines.append(f"Operating point used for B*/rho(B): residency={res['residency_pct_used']}%, "
                     f"bw={res['bw_gbps_used']} GB/s, precision={res['precision_used']}, "
                     f"SLO={res['slo_ms_used'] if res['slo_ms_used'] is not None else 'unconstrained'}.")
        lines.append("")
        lines.append(f"**B\\* = {res['b_star']}** ({res['b_star_note']})")
        lines.append("")
        lines.append("### E_union(B) and bytes/token")
        lines.append("")
        lines.append("| B | E_union(B) mean | bytes/token |")
        lines.append("|---|---|---|")
        for b in summary["batch_grid"]:
            eu = res["e_union_by_batch"].get(str(b), res["e_union_by_batch"].get(b))
            bpt = res["bytes_per_token"].get(str(b), res["bytes_per_token"].get(b))
            lines.append(f"| {b} | {eu:.2f} | {bpt/1e6:.3f} MB |")
        lines.append("")

        lines.append("### Per-token time breakdown (compute-bound vs transfer-bound)")
        lines.append("")
        lines.append("| B | compute (ms) | transfer (ms) | per-token time (ms) | rho | "
                     "total TPOT (ms) | feasible | t_compute source |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for row in res["b_star_table"]:
            lines.append(f"| {row['batch']} | {row['compute_component_ms']:.4f} | "
                         f"{row['transfer_component_ms']:.4f} | {row['per_token_time_ms']:.4f} | "
                         f"{row['rho']:.3f} | {row['total_tpot_ms']:.2f} | "
                         f"{'yes' if row['feasible_under_slo'] else 'no'} | {row['compute_provenance']} |")
        lines.append("")

        if res["batched_recall"]:
            lines.append("### Predictor recall for batched targets (new metric, E2 step 4)")
            lines.append("")
            lines.append("Recall@m for the *union* of experts a synthetic batch of B independent "
                         "requests needs, given each request's own top-m prediction (non-resident "
                         "only, matching the pilot's convention).")
            lines.append("")
            lines.append("> **Read `lift_over_random_batched`, not raw recall, when comparing across "
                         "batch sizes.** The candidate pool (pred_union) grows mechanically with B "
                         "since each of the B requests contributes its own top-m set, so raw recall "
                         "rises with batch even with zero predictive skill. `baseline_random_batched` "
                         "is the batch-scaled chance floor (analogous to the pilot's `baseline_random "
                         "= m/n_experts`); `lift_over_random_batched = recall_overall - baseline` is "
                         "what the predictor is actually contributing.")
            lines.append("")
            lines.append("| m | B | recall (overall) | recall (nonresident) | random baseline (batched) "
                         "| lift over baseline |")
            lines.append("|---|---|---|---|---|---|")
            for key, v in sorted(res["batched_recall"].items(), key=lambda kv: (kv[1]["m"], kv[1]["batch"])):
                lines.append(f"| {v['m']} | {v['batch']} | {v['recall_overall']:.3f} | "
                             f"{v['recall_nonresident']:.3f} | {v['baseline_random_batched']:.3f} | "
                             f"{v['lift_over_random_batched']:+.3f} |")
            lines.append("")
        else:
            lines.append("### Predictor recall for batched targets")
            lines.append("")
            lines.append("_Skipped this run (`--skip-recall`)._")
            lines.append("")

        lines.append("### Figures")
        lines.append("")
        for fig in res["figures"]:
            lines.append(f"- `out/figures/{Path(fig).name}`")
        lines.append("")

    default_analysis = [
        "*(placeholder -- not yet filled in. Once this section has real analysis, it will be "
        "preserved verbatim across re-runs instead of being reset to this checklist; only the "
        "data sections above ever get overwritten.)*",
        "",
        "- [ ] Does B* line up with intuition from the pilot's batch-8 erosion check "
        "(OLMoE's expert union widened 12.5% -> 47% of experts touched per step at B=8)?",
        "- [ ] Is the claim-check verdict above sensitive to the chosen (residency, bw, "
        "precision) operating point? Re-run with `--residency-pct`/`--bw-gbps`/`--precision` "
        "swept to check robustness before quoting it.",
        "- [ ] How much does batched-target recall degrade vs single-token recall "
        "(pilot's d1_m2k numbers: OLMoE 0.553, Mixtral 0.618) as B grows?",
        "- [ ] Cross-reference this B* against E6's later sweep (batch in {1,8,32}) once "
        "that experiment runs.",
    ]
    lines.extend(preserve_analysis_section(out_path, default_analysis))
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="experiments/e2_batching/out/batching_summary.json")
    ap.add_argument("--out", default="experiments/e2_batching/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.summary), Path(args.out))
