#!/usr/bin/env python3
"""Renders RESULTS.md from predictor_report.json. Called automatically at
the end of train_eval.py / run_e4.sh -- RESULTS.md is generated output,
don't hand-edit it (edit this template instead)."""
import json
from datetime import datetime, timezone
from pathlib import Path


def render(summary_path: Path, out_path: Path):
    s = json.loads(Path(summary_path).read_text())

    lines = []
    lines.append("# E4 Results: Predictor Upgrade and Confidence Calibration")
    lines.append("")
    lines.append(f"*Auto-generated by `train_eval.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e4.sh` to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/predictor_report.json`, `out/figures/`. Ran entirely on a laptop "
                 "(CPU) -- no GPU required for this experiment, per Experiments.md E4 itself "
                 "(\"trains in minutes on CPU/MPS\").")
    lines.append("")
    lines.append(f"Config: hidden_dim={s['hidden_dim']}, epochs={s['epochs']}, device={s['device']}, "
                 f"nonresident definition = top {s['c_nonresident_pct']}% by train-set popularity.")
    lines.append("")

    for model, m in s["per_model"].items():
        lines.append(f"## {model}")
        lines.append("")
        lines.append(f"n_layers={m['n_layers']}, n_experts={m['n_experts']}, k={m['k']}, "
                     f"train_reqs={m['n_train_reqs']}, test_reqs={m['n_test_reqs']}")
        lines.append("")

        lines.append("### Ablation: where does the predictive signal live? (d=1, m=k)")
        lines.append("")
        lines.append("| Variant | Recall@k overall | Recall@k nonresident | Layers used | Feature dim | Params |")
        lines.append("|---|---|---|---|---|---|")
        for row in m["ablation_table"]:
            params_str = f"{row['param_count']:,}" if row["param_count"] else "--"
            lines.append(f"| {row['variant']} | {row['recall_overall']:.3f} | "
                         f"{row['recall_nonresident']:.3f} | {row['n_layers_used']} | "
                         f"{row['feature_dim']} | {params_str} |")
        if m["skipped_variants"]:
            lines.append("")
            lines.append(f"**Skipped:** {m['skipped_variants']} -- no hidden-state file found "
                         f"(run `collect_hidden_states.py` on the GPU server, see design doc).")
        lines.append("")
        b = m["baseline_frequency_table"]
        lines.append(f"**Pilot frequency-table baseline** (unmodified, d=1, m=k): "
                     f"recall_overall={b['recall_overall']:.3f}, recall_nonresident={b['recall_nonresident']:.3f}")
        lines.append("")

        lines.append("### Exit criteria (Experiments.md E4's own wording)")
        lines.append("")
        lines.append("> \"Either recall@m=k improved >=8pp over the frequency table ... or it did not "
                     "(report the negative result, keep the frequency table).\"")
        lines.append("")
        lines.append(f"**Winning variant:** `{m['winning_variant']}` "
                     f"(+{m['pp_gain_over_baseline']:.1f}pp vs baseline, nonresident)" if m['winning_variant']
                     else "**No variant produced a usable result.**")
        lines.append("")
        lines.append(f"**Verdict:** {m['verdict']}")
        lines.append("")

        if m["recall_vs_bytes"]:
            lines.append(f"### Recall-vs-bytes curve (winning variant `{m['winning_variant']}`, "
                         f"precision={m['precision_used']})")
            lines.append("")
            lines.append("| m | Bytes/layer (MB) | Recall@m, nonresident |")
            lines.append("|---|---|---|")
            for r in m["recall_vs_bytes"]:
                lines.append(f"| {r['m']} | {r['bytes_per_layer']/1e6:.2f} | {r['recall_nonresident']:.3f} |")
            lines.append("")

        c = m["calibration"]
        if c:
            lines.append(f"### Calibration (winning variant, {c['n_pairs']:,} (row, candidate-expert) pairs)")
            lines.append("")
            lines.append(f"- ECE before temperature scaling: **{c['ece_before']:.4f}**")
            lines.append(f"- Fitted temperature T = **{c['temperature']:.3f}** "
                         f"({'overconfident, T>1 pulls probabilities toward 0.5' if c['temperature'] > 1.05 else 'underconfident, T<1 sharpens probabilities' if c['temperature'] < 0.95 else 'already close to calibrated'})")
            lines.append(f"- ECE after temperature scaling: **{c['ece_after']:.4f}**")
            lines.append("")
            lines.append("> Caveat: temperature was fit and evaluated on the SAME held-out test split "
                         "(no separate calibration-only split was carved out) -- the after-scaling ECE is "
                         "therefore mildly optimistic. Treat `ece_after` as an upper bound on how much "
                         "temperature scaling helps, not a final number for the report.")
            lines.append("")

        x = m["cross_domain_transfer"]
        if x:
            lines.append(f"### Cross-domain transfer (`{s.get('_xdomain_variant', 'ids_gate_entropy')}`, d=1, m=k)")
            lines.append("")
            lines.append("| Direction | Recall@k nonresident | Train reqs | Test reqs |")
            lines.append("|---|---|---|---|")
            for direction, res in x.items():
                if "error" in res:
                    lines.append(f"| {direction} | ERROR: {res['error']} | | |")
                else:
                    lines.append(f"| {direction} | {res['recall_nonresident']:.3f} | "
                                 f"{res['n_train_reqs']} | {res['n_test_reqs']} |")
            lines.append("")
            lines.append("Transfer holding up (similar recall to the same-domain ablation numbers above) "
                         "means the predictor is learning router/model structure, not dataset quirks.")
            lines.append("")

        lines.append("### Figures")
        lines.append("")
        for fig in m["figures"]:
            lines.append(f"- `out/figures/{Path(fig).name}`")
        lines.append("")

    lines.append("## Analysis notes (fill in after reviewing)")
    lines.append("")
    lines.append("- [ ] Does the winning ablation variant agree between OLMoE and Mixtral, or does "
                 "where-the-signal-lives differ by architecture (fine-grained vs coarse-grained)?")
    lines.append("- [ ] Is the 8pp exit-criteria bar met for both models, one, or neither? If neither, "
                 "that's the pilot's transition table already being near-sufficient -- a clean, reportable "
                 "negative result, not a failure of this experiment.")
    lines.append("- [ ] Does cross-domain recall drop sharply vs same-domain? A big drop would suggest "
                 "the predictor over-fit dataset quirks rather than learning router structure.")
    lines.append("- [ ] Re-run once `collect_hidden_states.py` has produced real data on the GPU server -- "
                 "does the hidden-state ablation change the winning variant?")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="experiments/e4_predictor/out/predictor_report.json")
    ap.add_argument("--out", default="experiments/e4_predictor/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.summary), Path(args.out))
