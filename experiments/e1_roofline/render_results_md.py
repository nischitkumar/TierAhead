#!/usr/bin/env python3
"""Renders RESULTS.md from roofline_summary.json. Called automatically at the
end of roofline.py / run_e1.sh -- RESULTS.md in this directory is therefore
generated output, not something to hand-edit (edit this template instead)."""
import json
import math
from datetime import datetime, timezone
from pathlib import Path


def render(summary_path: Path, out_path: Path):
    summary = json.loads(Path(summary_path).read_text())

    lines = []
    lines.append("# E1 Results: The MoE Tiering Roofline")
    lines.append("")
    lines.append(f"*Auto-generated by `roofline.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e1.sh` to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/roofline_summary.json`, `out/roofline_sweep.csv`, "
                 "`out/provisioning_table.csv`, `out/figures/`.")
    lines.append("")

    lines.append("## Compute-time provenance")
    lines.append("")
    lines.append("| Model | t_compute source |")
    lines.append("|---|---|")
    for m, prov in summary["compute_provenance"].items():
        note = "measured on this box's GPUs (measure_compute.py)" if prov == "measured_here" \
            else "FLOP/MFU analytical estimate (measure_compute.py not run, or no entry for this model)"
        lines.append(f"| {m} | `{prov}` -- {note} |")
    lines.append("")
    if any(p == "flop_estimate" for p in summary["compute_provenance"].values()):
        lines.append("> **Caveat:** one or more models used the FLOP-based estimate for t_compute "
                     "(Experiments.md E1 explicitly sanctions this as a placeholder \"until E3 lands\"). "
                     "Run `measure_compute.py` for that model and re-run `run_e1.sh` to replace the "
                     "estimate with a real measurement before treating rho values as load-bearing for "
                     "a paper claim.")
        lines.append("")

    lines.append("## E_union(B): mean distinct experts/layer at batch B")
    lines.append("")
    lines.append("| Model | " + " | ".join(f"B={b}" for b in summary["batch_grid"]) + " |")
    lines.append("|---|" + "---|" * len(summary["batch_grid"]))
    for m, by_batch in summary["e_union_by_batch"].items():
        row = " | ".join(f"{by_batch[str(b)] if str(b) in by_batch else by_batch.get(b, float('nan')):.2f}"
                          for b in summary["batch_grid"])
        lines.append(f"| {m} | {row} |")
    lines.append("")

    lines.append("## Headline: when is router-guided prefetch worth anything?")
    lines.append("")
    lines.append("(Auto-derived exit-criteria statement, Experiments.md E1: *\"You can state, in one "
                 "sentence with numbers, the condition under which router-guided prefetch is worth "
                 "anything.\"*)")
    lines.append("")
    for key, sentence in summary["headline_sentences"].items():
        lines.append(f"- **{key}**: {sentence}")
    lines.append("")

    lines.append("## Provisioning table")
    lines.append("")
    lines.append("Minimum link bandwidth (exact, continuous GB/s) to keep rho<1 at each "
                 "(model, precision, batch, residency) point, plus the nearest supported link "
                 f"tier from the swept grid {summary['bw_gbps_grid']} GB/s.")
    lines.append("")
    lines.append("| Model | Precision | Batch | Residency % | Required GB/s (rho=1) | "
                 "Nearest supported tier | t_compute source |")
    lines.append("|---|---|---|---|---|---|---|")
    for row in summary["provisioning_table"]:
        tier = row["nearest_supported_link_gbps"]
        # JSON round-trip (and pandas upcasting a mixed None/int column to
        # float64) can turn a missing tier into either None or float('nan') --
        # treat both as "no supported tier reaches rho=1 in this grid".
        no_tier = tier is None or (isinstance(tier, float) and math.isnan(tier))
        tier_str = "**exceeds 128 GB/s**" if no_tier else f"{tier:g}"
        lines.append(f"| {row['model']} | {row['precision']} | {row['batch']:g} | "
                     f"{row['residency_pct']:g} | {row['required_bw_gbps_for_rho1']:.1f} | "
                     f"{tier_str} | {row['compute_provenance']} |")
    lines.append("")

    lines.append("## Achievable points from the pilot (real, measured Coverage@C)")
    lines.append("")
    lines.append("These residency levels aren't hypothetical -- they're the pilot's actual "
                 "held-out-test-set Coverage@C, overlaid on the roofline as green stars.")
    lines.append("")
    for model, points in summary["achievable_points_from_pilot"].items():
        if not points:
            lines.append(f"- **{model}**: no pilot summary found at the expected path -- overlay skipped.")
            continue
        lines.append(f"- **{model}**:")
        for pt in points:
            lines.append(f"  - residency={pt['residency_pct']:g}% -> deployable coverage="
                         f"{pt['deployable_coverage']:.3f}, oracle coverage={pt['oracle_coverage']:.3f}")
    lines.append("")

    lines.append("## Figures")
    lines.append("")
    for fig in summary["figures"]:
        rel = Path(fig).name
        lines.append(f"- `out/figures/{rel}`")
    lines.append("")

    lines.append("## Analysis notes (fill in after reviewing the figures)")
    lines.append("")
    lines.append("- [ ] Does the rho=1 boundary land where Experiments.md predicted "
                 "(\"fine-grained MoE, expert <=~30MB, at batch>=8, >=50% residency, "
                 ">=64GB/s\")?")
    lines.append("- [ ] Do OLMoE and Mixtral anchor opposite sides of the boundary, as the "
                 "reframing in Experiments.md §0 claims?")
    lines.append("- [ ] Which (model, precision) combinations require E7's byte-reduction "
                 "mechanism outright (never reach rho<1 in the swept grid)?")
    lines.append("- [ ] Any surprises vs the FLOP-estimate assumption once measure_compute.py's "
                 "real numbers are in?")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="experiments/e1_roofline/out/roofline_summary.json")
    ap.add_argument("--out", default="experiments/e1_roofline/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.summary), Path(args.out))
