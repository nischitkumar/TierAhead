#!/usr/bin/env python3
"""Renders RESULTS.md from calibration_report.json. Called automatically at
the end of build_calibration_report.py / run_e3.sh -- RESULTS.md in this
directory is generated output, not something to hand-edit (edit this
template instead)."""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.results_md import preserve_analysis_section  # noqa: E402


def render(report_path: Path, out_path: Path):
    report = json.loads(Path(report_path).read_text())
    out_path = Path(out_path)

    lines = []
    lines.append("# E3 Results: Hardware Calibration Ladder")
    lines.append("")
    lines.append(f"*Auto-generated by `build_calibration_report.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e3.sh` (or `build_calibration_report.py`) to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/calibration_report.json`, plus whichever of `out/calib_transfer.json`, "
                 "`out/calib_e2e.json`, `out/calib_nf4_fidelity.json`, and "
                 "`../e1_roofline/out/calib_compute.json` exist.")
    lines.append("")

    lines.append("## Methodology / provenance table")
    lines.append("")
    lines.append("Experiments.md E3's own framing: *\"a methodology table in the report listing every "
                 "simulator parameter and whether it is measured here, measured in cited work, or "
                 "vendor-specified\"* — this table is that deliverable, generated directly from whatever "
                 "calibration files actually exist on disk (never a fabricated placeholder).")
    lines.append("")
    lines.append("| Parameter | Status | Detail |")
    lines.append("|---|---|---|")
    n_missing = 0
    for row in report["provenance_table"]:
        if row["status"].startswith("MISSING"):
            n_missing += 1
        lines.append(f"| {row['parameter']} | `{row['status']}` | {row['detail']} |")
    lines.append("")

    if n_missing:
        lines.append(f"> **{n_missing}/{len(report['provenance_table'])} parameter(s) still MISSING** -- "
                     "this box (where this file was generated) has no CUDA GPU, so none of E3's own GPU "
                     "scripts (`measure_transfer.py`, `e2e_offload_runner.py`, `nf4_fidelity.py`) could be "
                     "run here. Run `run_e3.sh` on the GPU server and re-run this script (or let `run_e3.sh` "
                     "do it automatically) to fill these in.")
    else:
        lines.append("> All parameters measured. Simulator parameter file is fully populated with "
                     "provenance for each entry — Experiments.md E3's exit criteria's first half.")
    lines.append("")

    lines.append("## Transfer-time model fit (t = alpha + size/beta)")
    lines.append("")
    if report["transfer_fit"] is None:
        lines.append("Not yet available -- see `transfer (alpha/beta)` row above.")
    else:
        fit = report["transfer_fit"]
        lines.append(f"- **alpha (fixed overhead):** {fit['alpha_ms']:.4f} ms")
        lines.append(f"- **beta (asymptotic bandwidth):** {fit['beta_bytes_per_ms']/1e6:.1f} MB/ms "
                     f"(~{fit['beta_bytes_per_ms']/1e3:.0f} GB/s)")
        lines.append(f"- **R^2:** {fit['r_squared']:.4f} over {fit['n_points']} measured sizes")
        lines.append("")
        lines.append("This is the exact functional form Experiments.md says to reuse for CXL with "
                     "literature-derived alpha/beta swapped in for these PCIe-measured ones.")
    lines.append("")

    lines.append("## PCIe offload-policy ordering (E3 step 3 exit criteria)")
    lines.append("")
    lines.append("Expected (Experiments.md, translated to TPOT-latency units — see `policy_check.py`'s "
                 "docstring): `next-layer-topk <= static-hot <= none`.")
    lines.append("")
    if report["policy_ordering_check"] is None:
        lines.append("Not yet available -- see `e2e offload policy ordering` row above.")
    else:
        lines.append("| Residency | Passed | Message |")
        lines.append("|---|---|---|")
        for level, (passed, msg) in report["policy_ordering_check"].items():
            lines.append(f"| {level}% | {'✅' if passed else '❌'} | {msg} |")
    lines.append("")

    lines.append("## NF4 routing-fidelity spot-check (OLMoE, pilot open item #2)")
    lines.append("")
    if report["nf4_fidelity"] is None:
        lines.append("Not yet available -- see `nf4 routing fidelity (olmoe)` row above.")
    else:
        nf4 = report["nf4_fidelity"]
        lines.append(f"- Mean top-k Jaccard agreement (fp16 vs nf4), across layers: "
                     f"**{nf4.get('mean_jaccard_similarity', float('nan')):.3f}**")
        lines.append(f"- n_prompts: {nf4.get('n_prompts')}")
        per_layer = nf4.get("per_layer_jaccard", {})
        if per_layer:
            lines.append("")
            lines.append("| Layer | Jaccard(fp16, nf4) |")
            lines.append("|---|---|")
            for layer in sorted(per_layer, key=lambda x: int(x)):
                lines.append(f"| {layer} | {per_layer[layer]:.3f} |")
        lines.append("")
        lines.append("Mixtral's own NF4 fidelity is not independently measured here (Mixtral fp16 doesn't "
                     "fit for a same-model fp16-vs-nf4 comparison on this box) — cite QLoRA "
                     "(arXiv:2305.14314) for that side, per Experiments.md's own instruction.")
    lines.append("")

    lines.append("## Figures")
    lines.append("")
    figs = report.get("figures", [])
    if not figs:
        lines.append("None yet (needs the transfer calibration to exist).")
    for fig in figs:
        lines.append(f"- `out/figures/{Path(fig).name}`")
    lines.append("")

    default_analysis = [
        "*(placeholder -- not yet filled in. Once this section has real analysis, it will be "
        "preserved verbatim across re-runs instead of being reset to this checklist; only the "
        "data sections above ever get overwritten.)*",
        "",
        "- [ ] Does the PCIe policy ordering (`next-layer-topk <= static-hot <= none`) hold at both "
        "swept residency levels?",
        "- [ ] How does the measured PCIe alpha/beta compare to the CXL alpha/beta values cited from "
        "Sun et al. (ISCA'23) / Ji et al. (MICRO'24)? Are they the same order of magnitude?",
        "- [ ] Is OLMoE's fp16-vs-nf4 routing agreement high enough to trust the project's Mixtral-NF4 "
        "trace-collection numbers by analogy?",
        "- [ ] Is every simulator parameter E6 will need now covered, or is something still missing "
        "from this table?",
    ]
    lines.extend(preserve_analysis_section(out_path, default_analysis))
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default="experiments/e3_calibration/out/calibration_report.json")
    ap.add_argument("--out", default="experiments/e3_calibration/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.report), Path(args.out))
