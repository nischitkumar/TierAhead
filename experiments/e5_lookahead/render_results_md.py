#!/usr/bin/env python3
"""Renders RESULTS.md from lookahead_report.json. Called automatically at
the end of lookahead.py / run_e5.sh -- generated output, don't hand-edit."""
import json
from datetime import datetime, timezone
from pathlib import Path


def render(summary_path: Path, out_path: Path):
    s = json.loads(Path(summary_path).read_text())

    lines = []
    lines.append("# E5 Results: Lookahead Depth and Pipelined Prefetch")
    lines.append("")
    lines.append(f"*Auto-generated by `lookahead.py` / `render_results_md.py` on "
                 f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
                 f"Do not hand-edit; re-run `run_e5.sh` to regenerate.*")
    lines.append("")
    lines.append("Source data: `out/lookahead_report.json`, `out/figures/`. Ran entirely on a laptop "
                 "(CPU) -- reuses E4's predictor machinery, no GPU required.")
    lines.append("")
    lines.append(f"Config: d_values={s['d_values']}, hidden_dim={s['hidden_dim']}, epochs={s['epochs']}, "
                 f"fetch_batch={s['fetch_batch']}, precision={s['precision']}, "
                 f"recall threshold for 'useful depth' = {next(iter(s['per_model'].values()))['recall_threshold']}.")
    lines.append("")

    for model, m in s["per_model"].items():
        lines.append(f"## {model}")
        lines.append("")
        lines.append(f"n_layers={m['n_layers']}, n_experts={m['n_experts']}, k={m['k']}")
        lines.append("")

        lines.append("### Recall@k, nonresident vs depth: direct vs chained")
        lines.append("")
        lines.append("| d | Direct recall | Layers used | Chained recall | Gap (direct - chained) |")
        lines.append("|---|---|---|---|---|")
        for d_str, r in sorted(m["direct_recall_by_d"].items(), key=lambda kv: int(kv[0])):
            d = int(d_str)
            c = m["chained_recall_by_d"].get(d_str, float("nan"))
            gap = r - c if not (r != r or c != c) else float("nan")
            lines.append(f"| {d} | {r:.3f} | {m['direct_layers_used'][d_str]} | {c:.3f} | {gap:+.3f} |")
        lines.append("")

        useful_d = m["max_useful_depth"]
        lines.append(f"### Exit criteria: maximum useful lookahead depth (recall >= {m['recall_threshold']})")
        lines.append("")
        if useful_d is not None:
            lines.append(f"**d={useful_d}** is the smallest depth at which recall stays >= "
                         f"{m['recall_threshold']} for every deeper depth swept too (not just a one-off "
                         f"peak) -- Experiments.md's own expected shape: \"OLMoE-class fully served at "
                         f"d=1-2; Mixtral-class requires d>=8 and byte reduction.\"")
        else:
            lines.append(f"**No swept depth reaches recall >= {m['recall_threshold']}** and holds it -- "
                         f"this model needs deeper lookahead than tested here, or E7's byte-reduction "
                         f"mechanism instead of (or in addition to) more lookahead.")
        lines.append("")

        lines.append("### Feasible fetch size vs depth (bytes fetchable within a d-layer compute window)")
        lines.append("")
        prov = m["queue_sim"]["compute_provenance"]
        lines.append(f"t_compute source: `{prov}`" +
                     (" -- **run E1's/E3's measure_compute.py and re-run this with --calib for a real number "
                      "before quoting these bytes in a report.**" if prov == "flop_estimate" else "."))
        lines.append("")
        lines.append(f"1 expert at this precision = {m['feasible_fetch'][0]['expert_bytes']/1e6:.2f} MB.")
        lines.append("")
        lines.append("| d | BW (GB/s) | Bytes fetchable (MB) | >= 1 expert? |")
        lines.append("|---|---|---|---|")
        for row in sorted(m["feasible_fetch"], key=lambda r: (r["d"], r["bw_gbps"])):
            ok = "yes" if row["bytes_fetchable"] >= row["expert_bytes"] else "no"
            lines.append(f"| {row['d']} | {row['bw_gbps']:g} | {row['bytes_fetchable']/1e6:.2f} | {ok} |")
        lines.append("")

        lines.append("### Prefetch queue simulation (bounded buffer, deterministic arrivals)")
        lines.append("")
        lines.append(f"t_layer = {m['queue_sim']['t_layer_ms']:.4f} ms/layer (batch={s['fetch_batch']}); "
                     f"worst-case per-layer bytes = {m['queue_sim']['expert_total_bytes_worstcase']/1e6:.2f} MB "
                     f"(k experts, none resident).")
        lines.append("")
        lines.append("| BW (GB/s) | rho (load) | Q | Mean occupancy | Link utilization | Drop rate |")
        lines.append("|---|---|---|---|---|---|")
        for bw_str, by_q in m["queue_sim"]["by_bw"].items():
            for q_str, res in sorted(by_q.items(), key=lambda kv: int(kv[0])):
                lines.append(f"| {bw_str} | {res['rho']:.2f} | {q_str} | {res['mean_occupancy']:.2f} | "
                             f"{res['link_utilization']:.2f} | {res['drop_rate']:.3f} |")
        lines.append("")
        lines.append("> Deterministic-queue result: when rho<=1 (link keeps up), queue depth Q doesn't "
                     "matter at all -- occupancy/utilization are already at their floor and nothing is "
                     "ever dropped. When rho>1, a bigger Q doesn't reduce the steady-state drop rate "
                     "either (it's fixed at 1-1/rho) -- it only delays how long the fill-up transient "
                     "takes. **Making the prefetch buffer deeper never fixes an overloaded link** -- only "
                     "more bandwidth or fewer bytes (E7) does.")
        lines.append("")

    if s.get("figures"):
        lines.append("## Figures")
        lines.append("")
        for fig in s["figures"]:
            lines.append(f"- `out/figures/{Path(fig).name}`")
        lines.append("")

    lines.append("## Analysis notes (fill in after reviewing)")
    lines.append("")
    lines.append("- [ ] Does the direct-vs-chained gap widen with d, as Experiments.md predicts "
                 "(\"chaining compounds error\")? Report the d at which the gap becomes practically "
                 "significant, not just statistically nonzero.")
    lines.append("- [ ] Cross-reference max_useful_depth against E1's roofline: at that depth's feasible "
                 "fetch size, does it actually cover a real expert's byte size for this model/precision?")
    lines.append("- [ ] Re-run with a real `--calib` (E1's/E3's measure_compute.py output) once available "
                 "on the GPU server -- flop_estimate rho values shouldn't be quoted as final.")
    lines.append("")

    out_path.write_text("\n".join(lines))
    print(f"[render_results_md] wrote {out_path}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="experiments/e5_lookahead/out/lookahead_report.json")
    ap.add_argument("--out", default="experiments/e5_lookahead/RESULTS.md")
    args = ap.parse_args()
    render(Path(args.summary), Path(args.out))
